function updateQuestion(signature, lesson, order) {
  const renderedVisual = lesson.visualType.includes("diagram") || lesson.visualType === "concept_map"
    ? fence("mermaid", md(lesson.visual).split("\n"))
    : md(lesson.visual);
  const interviewContent = lesson.interview.map(md).join("\n\n");
  return {
    id: signature.id,
    slug: signature.slug,
    question: md(lesson.question),
    title: md(lesson.title),
    direct_answer: md(lesson.direct),
    layout_type: "three-zone-learning",
    difficulty: order === 3 ? "medium" : "easy",
    importance: "high",
    reading_time_minutes: 9,
    answer: {
      sections: [
        { type: "key_points", title: "Quick revision", items: lesson.quick.map(md) },
        {
          type: "speakable_answer",
          title: "Interview answer",
          answerSize: proseWords(interviewContent) < 220 ? "compact" : "standard",
          content: interviewContent,
        },
        { type: "deep_explanation", title: md(lesson.deepTitle), content: lesson.deep.map(md).join("\n\n") },
        { type: lesson.visualType, title: md(lesson.visualTitle), content: renderedVisual },
        { type: "code_example", title: md(lesson.codeTitle), content: fence("typescript", lesson.code.map(md)) },
      ],
    },
    followup_questions: lesson.followups.map(md),
    order,
    seo: {
      metaTitle: `${md(lesson.title)} | Angular interview | InterviewExplainer`,
      metaDescription: metaDescription(lesson.direct),
    },
  };
}

let questionCount = 0;
for (const [topicSlug, topicLessons] of Object.entries(lessons)) {
  const file = path.join(moduleRoot, topicSlug, "complete-qa.json");
  const document = JSON.parse(fs.readFileSync(file, "utf8"));
  if (!Array.isArray(document.questions) || ![3, 5].includes(document.questions.length)) {
    throw new Error(`${topicSlug}: expected the three curated records or five source records`);
  }
  const actualStable = document.questions.slice(0, 3).map(({ id, slug }) => ({ id, slug }));
  if (JSON.stringify(actualStable) !== JSON.stringify(signatures[topicSlug])) {
    throw new Error(`${topicSlug}: stable IDs or slugs changed`);
  }
  if (topicLessons.length !== 3) throw new Error(`${topicSlug}: expected exactly three lessons`);
  document.topic = topicTitles[topicSlug];
  document.topicSlug = topicSlug;
  document.questions = topicLessons.map((lesson, index) => updateQuestion(signatures[topicSlug][index], lesson, index + 1));
  fs.writeFileSync(file, `${JSON.stringify(document, null, 2)}\n`);
  questionCount += document.questions.length;
}

