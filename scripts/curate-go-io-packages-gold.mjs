function metaDescription(value) {
  const plain = md(value).replace(/[`*_#>|\[\](){}]/g, "").replace(/\s+/g, " ").trim();
  if (plain.length <= 157) return plain;
  return `${plain.slice(0, 154).replace(/\s+\S*$/, "")}…`;
}

function renderVisual(lesson) {
  const content = lesson.visual.map(md).join("\n");
  return lesson.visualType.includes("diagram") ? fence("mermaid", content.split("\n")) : content;
}

function updateQuestion(original, lesson, order) {
  const {
    interviewer_intent: _interviewerIntent,
    speakable_v2: _speakableV2,
    ...stable
  } = original;

  return {
    ...stable,
    question: md(lesson.question),
    title: md(lesson.title),
    direct_answer: md(lesson.direct),
    layout_type: "concept-explanation",
    difficulty: "easy",
    importance: "high",
    reading_time_minutes: 8,
    answer: {
      sections: [
        {
          type: "key_points",
          title: "Quick revision",
          items: lesson.quick.map(md),
        },
        {
          type: "speakable_answer",
          title: "Interview answer",
          answerSize: "compact",
          content: paragraphs(lesson.interview),
        },
        {
          type: "overview",
          title: md(lesson.overviewTitle),
          content: paragraphs(lesson.overview),
        },
        {
          type: "deep_explanation",
          title: md(lesson.deepTitle),
          content: paragraphs(lesson.deep),
        },
        {
          type: lesson.visualType,
          title: md(lesson.visualTitle),
          content: renderVisual(lesson),
        },
        {
          type: "code_example",
          title: md(lesson.codeTitle),
          content: fence("go", formatGo(lesson.code)),
        },
      ],
    },
    followup_questions: lesson.followups.map(md),
    order,
    seo: {
      metaTitle: `${md(lesson.title)} | Go interview question | InterviewExplainer`,
      metaDescription: metaDescription(lesson.direct),
    },
  };
}

for (const [topicSlug, topicLessons] of Object.entries(lessons)) {
  if (topicLessons.length !== 3) {
    throw new Error(`${topicSlug}: expected exactly three curated lessons`);
  }
  const file = path.join(moduleRoot, topicSlug, "complete-qa.json");
  const document = JSON.parse(fs.readFileSync(file, "utf8"));
  if (document.questions.length < 3) {
    throw new Error(`${topicSlug}: needs at least three stable source records`);
  }
  const retained = document.questions.slice(0, 3);
  document.topic = topicTitles[topicSlug];
  document.topicSlug = topicSlug;
  document.questions = topicLessons.map((lesson, index) =>
    updateQuestion(retained[index], lesson, index + 1),
  );
  fs.writeFileSync(file, `${JSON.stringify(document, null, 2)}\n`);
}

